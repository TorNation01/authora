def _apply_premium(defn: dict[str, Any]) -> dict[str, Any]:
    """Apply premium overrides if this template has them."""
    overrides = get_premium_overrides()
    slug = defn.get("slug")
    if slug and slug in overrides:
        return {**defn, **overrides[slug]}
    return defn


